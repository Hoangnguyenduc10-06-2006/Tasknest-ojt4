ALTER TABLE users
    ADD COLUMN job_title VARCHAR(100) NOT NULL DEFAULT '',
    ADD COLUMN bio VARCHAR(500) NOT NULL DEFAULT '';

CREATE TABLE user_avatars (
    user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    image_data MEDIUMBLOB NOT NULL,
    CONSTRAINT fk_avatar_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT ck_avatar_size CHECK (OCTET_LENGTH(image_data) BETWEEN 1 AND 5242880)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;
