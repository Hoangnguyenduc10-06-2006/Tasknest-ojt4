CREATE TABLE professional_member_profiles (
    user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    display_name VARCHAR(150) NOT NULL,
    headline VARCHAR(150) NOT NULL DEFAULT '',
    about VARCHAR(2000) NOT NULL,
    location VARCHAR(100) NOT NULL DEFAULT '',
    experience_years TINYINT UNSIGNED NULL,
    skills JSON NOT NULL,
    desired_roles JSON NOT NULL,
    collaboration_modes JSON NOT NULL,
    availability VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'BUSY',
    weekly_hours TINYINT UNSIGNED NULL,
    github_url VARCHAR(2048) NULL,
    linkedin_url VARCHAR(2048) NULL,
    website_url VARCHAR(2048) NULL,
    portfolio_items JSON NOT NULL,
    is_public BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT ck_professional_experience CHECK (experience_years IS NULL OR experience_years BETWEEN 0 AND 50),
    CONSTRAINT ck_professional_hours CHECK (weekly_hours IS NULL OR weekly_hours BETWEEN 1 AND 80),
    CONSTRAINT ck_professional_availability CHECK (availability IN ('AVAILABLE','LOOKING_FOR_TEAM','BUSY'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;
