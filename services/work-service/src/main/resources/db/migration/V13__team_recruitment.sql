CREATE TABLE team_openings (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    team_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    skills VARCHAR(300) NOT NULL,
    work_mode VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    weekly_hours INT NOT NULL,
    slots INT NOT NULL,
    closes_on DATE NOT NULL,
    status VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'OPEN',
    version BIGINT NOT NULL DEFAULT 0,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_hash BINARY(32) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    FOREIGN KEY (team_id) REFERENCES dev_teams(id),
    UNIQUE KEY uq_opening_request (team_id,request_id),
    INDEX ix_opening_team (team_id,id),
    INDEX ix_opening_board (status,closes_on,id),
    CONSTRAINT ck_opening_status CHECK (status IN ('OPEN','PAUSED','CLOSED')),
    CONSTRAINT ck_opening_mode CHECK (work_mode IN ('REMOTE','HYBRID','ONSITE')),
    CONSTRAINT ck_opening_limits CHECK (weekly_hours BETWEEN 1 AND 80 AND slots BETWEEN 1 AND 20)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

CREATE TABLE team_applications (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    opening_id BIGINT NOT NULL,
    user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    display_name VARCHAR(150) NOT NULL,
    introduction VARCHAR(2000) NOT NULL,
    skills VARCHAR(300) NOT NULL,
    weekly_hours INT NOT NULL,
    status VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING',
    feedback VARCHAR(1000) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    reviewed_at DATETIME(6) NULL,
    FOREIGN KEY (opening_id) REFERENCES team_openings(id),
    UNIQUE KEY uq_opening_applicant (opening_id,user_id),
    INDEX ix_application_user (user_id,id),
    CONSTRAINT ck_application_status CHECK (status IN ('PENDING','ACCEPTED','REJECTED','WITHDRAWN')),
    CONSTRAINT ck_application_hours CHECK (weekly_hours BETWEEN 1 AND 80)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;
