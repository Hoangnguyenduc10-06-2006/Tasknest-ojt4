CREATE TABLE customer_project_requests (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    customer_user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    title VARCHAR(100) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    skills VARCHAR(300) NOT NULL,
    budget_min DECIMAL(12,0) NULL,
    budget_max DECIMAL(12,0) NULL,
    desired_delivery DATE NOT NULL,
    reference_url VARCHAR(2048) NULL,
    status VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'DRAFT',
    project_id BIGINT NULL,
    creation_request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    creation_hash BINARY(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uq_customer_request (customer_user_id,creation_request_id),
    FOREIGN KEY (project_id) REFERENCES projects(id),
    INDEX ix_request_discovery (status,created_at,id),
    INDEX ix_request_customer (customer_user_id,updated_at,id),
    CONSTRAINT ck_customer_request_status CHECK (status IN ('DRAFT','OPEN','PAUSED','CLOSED','AWARDED')),
    CONSTRAINT ck_customer_request_budget CHECK ((budget_min IS NULL OR budget_min>=0) AND (budget_max IS NULL OR budget_max>=0) AND (budget_min IS NULL OR budget_max IS NULL OR budget_max>=budget_min)),
    CONSTRAINT ck_customer_request_award CHECK ((status='AWARDED')=(project_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

CREATE TABLE team_project_proposals (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    request_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    submitted_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_version BIGINT NOT NULL,
    plan VARCHAR(4000) NOT NULL,
    amount DECIMAL(12,0) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    status VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'SUBMITTED',
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    accepted_request_id BIGINT GENERATED ALWAYS AS (CASE WHEN status='ACCEPTED' THEN request_id ELSE NULL END) STORED,
    UNIQUE KEY uq_request_team_proposal (request_id,team_id),
    UNIQUE KEY uq_request_accepted_proposal (accepted_request_id),
    FOREIGN KEY (request_id) REFERENCES customer_project_requests(id),
    FOREIGN KEY (team_id) REFERENCES dev_teams(id),
    INDEX ix_proposal_team (team_id,updated_at,id),
    CONSTRAINT ck_team_proposal_status CHECK (status IN ('SUBMITTED','WITHDRAWN','ACCEPTED','DECLINED')),
    CONSTRAINT ck_team_proposal_amount CHECK (amount>0),
    CONSTRAINT ck_team_proposal_dates CHECK (ends_on>=starts_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;
